export type TKey = keyof typeof translations['en'];

export function t(
  lang: Lang,
  key: TKey,
  vars?: Record<string, string>
): string {
  let s: string = translations[lang][key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replace(`{${k}}`, v);
    }
  }
  return s;
}

